import { settingsTabsFor } from '@/modules/settings/contracts';
import type { ShellViewer } from '@/views/StaffShell';

/**
 * A frozen copy of the menu rule before the UX redesign R1 (navItemsFor in
 * src/views/StaffShell.tsx at the R0 build, b735946), reduced to the
 * addresses it offered, in order. It is the oracle for the R1 tests: the new
 * grouped menu (src/app/app/sections.ts) must offer exactly these addresses
 * to every person, through its links or its Accounts section tabs, so the
 * regrouping adds no access and hides no page. Each flag here was written to
 * match the page's own gate, so an address outside this list is a page that
 * refuses the person. Do not edit this file to make a test pass.
 */
export function legacyMenuHrefs(viewer: ShellViewer): string[] {
  const items: string[] = ['/app'];
  if (viewer.canSeeLeads) items.push('/app/leads');
  items.push('/app/deals');
  if (viewer.canSeeQuotations) items.push('/app/quotations', '/app/itineraries');
  if (viewer.canSeePurchaseTasks) items.push('/app/purchase', '/app/purchase/suppliers', '/app/purchase/rate-contracts');
  if (viewer.canSeePurchasePayments) items.push('/app/purchase/payments');
  if (viewer.canSeeApprovals) items.push('/app/approvals');
  if (viewer.canSeeFlightTasks) items.push('/app/flight');
  if (viewer.canSeeVisaDesk) items.push('/app/visa');
  if (viewer.canUseAccounts) {
    items.push(
      '/app/accounts',
      ...(viewer.canCheckCustomers ? ['/app/accounts/customers'] : []),
      '/app/accounts/claims',
      '/app/accounts/go-ahead',
      '/app/accounts/supplier-payments',
      '/app/accounts/supplier-invoices',
      '/app/accounts/funding',
      '/app/accounts/expenses',
      '/app/accounts/cash',
      '/app/accounts/destinations',
    );
  } else if (viewer.canCheckCustomers) {
    items.push('/app/accounts/customers');
  }
  if (viewer.canSeeAccountsDesk) {
    items.push(
      '/app/accounts/records',
      '/app/accounts/dues',
      '/app/accounts/documents',
      '/app/accounts/refunds',
      '/app/accounts/small-balances',
      '/app/accounts/tally',
      ...(viewer.canSeePurchaseTasks ? [] : ['/app/purchase/rate-contracts']),
    );
  } else if (viewer.canSeeBranchMoney) {
    items.push('/app/accounts/records', '/app/accounts/dues', '/app/accounts/documents', '/app/accounts/small-balances');
  } else if (viewer.canSeeOwnDues) {
    items.push('/app/accounts/dues');
  }
  const settingsTabs = settingsTabsFor({
    canAdministerStaff: viewer.canAdministerStaff,
    canManageGrants: viewer.canManageGrants,
    canManageIntegration: !!viewer.canManageIntegration,
    canOpenBitrixConnection: !!viewer.canOpenBitrixConnection,
    canManageFinancePolicy: !!viewer.canManageFinancePolicy,
    canImport: !!viewer.canImport,
  });
  if (settingsTabs.length > 0) items.push(settingsTabs[0]!.href);
  return items;
}
